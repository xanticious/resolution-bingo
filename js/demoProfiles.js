// Helper function to generate a complete demo profile with all data
export function generateDemoProfile(personaIndex, state) {
  const persona = DEMO_PERSONAS[personaIndex];
  if (!persona) return null;

  const profileId = generateUUID();
  const now = new Date().toISOString();

  // Create profile
  const profile = {
    id: profileId,
    name: `${persona.name} (${persona.age}, ${persona.occupation})`,
    createdAt: now,
    updatedAt: now,
  };

  // Get or create life categories
  const categories = new Map();
  const suggestedCategories = [
    'Health',
    'Social',
    'Creative',
    'Career',
    'Nutrition',
    'Exercise',
    'Friendships',
    'Getting out of the House',
    'Self-Care',
    'Finances',
    'Education',
    'Travel',
  ];

  // Color palette for categories
  const colorPalette = [
    '#FF6B6B',
    '#4ECDC4',
    '#45B7D1',
    '#FFA07A',
    '#98D8C8',
    '#F7DC6F',
    '#BB8FCE',
    '#85C1E2',
    '#F8B739',
    '#52C4A8',
    '#E06377',
    '#5DADE2',
  ];

  persona.resolutions.forEach((res) => {
    if (!categories.has(res.categoryName)) {
      const colorIndex = categories.size % colorPalette.length;
      categories.set(res.categoryName, {
        id: generateUUID(),
        profileId: profileId,
        name: res.categoryName,
        color: colorPalette[colorIndex],
        isCustom: !suggestedCategories.includes(res.categoryName),
        createdAt: now,
      });
    }
  });

  // Create resolutions
  const resolutions = persona.resolutions.map((res, index) => ({
    id: generateUUID(),
    profileId: profileId,
    text: res.text,
    frequency: res.frequency,
    excitementLevel: res.excitementLevel,
    lifeCategoryId: categories.get(res.categoryName).id,
    order: index,
    createdAt: now,
    updatedAt: now,
  }));

  return {
    profile,
    categories: Array.from(categories.values()),
    resolutions,
    hideOptionalFields: persona.hideOptionalFields || false,
  };
}

